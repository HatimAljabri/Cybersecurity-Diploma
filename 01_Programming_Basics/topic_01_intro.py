"""
ملخص أساسيات بايثون

المواضيع المغطاة: الطباعة، التعليقات، الجمل البرمجية، المسافات البادئة، وتشغيل الكود.
"""

# ==========================================
# 1. الطباعة (Print)
# لعرض المخرجات على الشاشة. النصوص بين علامتي تنصيص، والأرقام تُكتب مباشرة.
# ==========================================
print("Hatim")
print(26)

# ==========================================
# 2. التعليقات (Comments)
# ملاحظات لتوضيح الكود يقرأها المبرمج ويتجاهلها الحاسوب.
# ==========================================

# علامة المربع (Hash) تُستخدم لتعليق في سطر واحد:
print("Hello") # دالة طباعة ترحيبية

'''
علامات التنصيص الثلاثية تُستخدم لكتابة 
تعليقات وملاحظات طويلة تمتد لعدة أسطر.
'''

# ==========================================
# 3. البرنامج والجملة البرمجية (Program and Statement)
# Statement: أمر واحد يُعطى لبايثون.
# Program: الكود الكامل المكون من تسلسل الجمل.
# ==========================================
name = "Hatim"    # Statement 1
age = 26          # Statement 2
print(name, age)  # Statement 3

# ==========================================
# 4. المسافات البادئة (Indentation)
# قاعدة أساسية لتحديد الكتل البرمجية، وغيابها يسبب خطأ (IndentationError).
# ==========================================
if 26 > 20:
    # هذه المسافة البادئة (4 مسافات) ضرورية جداً
    print("العمر أكبر من 20")

# ==========================================
# 5. تشغيل الكود (Running Code)
# الخطوة النهائية حيث يقرأ المفسر (Interpreter) البرنامج وينفذ الأوامر.
# ==========================================
